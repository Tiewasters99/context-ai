// Compile docs/orchestrator/known-issues/*.md into lib/known-issues.generated.mjs.
//
//   node scripts/build-known-issues.mjs           write it
//   node scripts/build-known-issues.mjs --check   exit 1 if the committed copy is stale
//
// Run it (and commit the output) whenever an entry changes. It also records
// main's first-parent commit order and dates, so the lookup can tell a person
// whether a fix is in the version their tab is running. That needs full git
// history, which a shallow CI checkout lacks: with --check on a shallow clone
// only the entries are compared, and the order table is taken as committed.

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { parseEntry, entryProblems } from '../lib/known-issues.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'docs', 'orchestrator', 'known-issues');
const OUT = path.join(ROOT, 'lib', 'known-issues.generated.mjs');
const CHECK = process.argv.includes('--check');

export function readEntries() {
  const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.md') && !f.startsWith('_') && f !== 'README.md').sort();
  const entries = files.map((f) => {
    const e = parseEntry(fs.readFileSync(path.join(DIR, f), 'utf8'), f);
    if (`${e.id}.md` !== f) throw new Error(`${f}: id "${e.id}" must match the file name`);
    return e;
  });
  const problems = entries.flatMap(entryProblems);
  const ids = entries.map((e) => e.id);
  for (const id of ids) if (ids.indexOf(id) !== ids.lastIndexOf(id)) problems.push(`${id}: duplicate id`);
  if (problems.length) throw new Error(`known issues are not sound:\n  ${problems.join('\n  ')}`);
  return entries;
}

function git(args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
}

function mainHistory() {
  try {
    if (git(['rev-parse', '--is-shallow-repository']) === 'true') return null;
    const ref = (() => { try { git(['rev-parse', '--verify', 'origin/main']); return 'origin/main'; } catch { return 'HEAD'; } })();
    const lines = git(['log', '--first-parent', '--reverse', '--format=%H %cs', '-n', '3000', ref]).split('\n').filter(Boolean);
    return lines.map((l) => { const [h, d] = l.split(' '); return [h.slice(0, 12), d]; });
  } catch {
    return null;
  }
}

function render(entries, history) {
  const data = {
    entries,
    order: history.map(([c]) => c),
    dates: history,
  };
  return `// GENERATED by scripts/build-known-issues.mjs from docs/orchestrator/known-issues/.\n// Do not edit by hand; edit the entry and re-run the script.\nexport default ${JSON.stringify(data, null, 1)};\n`;
}

const entries = readEntries();
let history = mainHistory();
let committed = null;
try { committed = (await import(`file://${OUT.replace(/\\/g, '/')}`)).default; } catch { /* first run */ }

if (!history) {
  if (!committed) throw new Error('No git history (shallow clone?) and no committed table to fall back on.');
  history = committed.dates;
}
for (const e of entries.filter((x) => x.status === 'fixed')) {
  const c = e.fixed_in.slice(0, 12);
  if (!history.some(([h]) => h === c)) {
    throw new Error(`${e.id}: fixed_in ${e.fixed_in} is not a first-parent commit on main — use the merge commit of the fix`);
  }
}

const next = render(entries, history);
if (CHECK) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  const sameEntries = committed && JSON.stringify(committed.entries) === JSON.stringify(entries);
  if (!sameEntries) {
    console.error('lib/known-issues.generated.mjs is stale: run  node scripts/build-known-issues.mjs  and commit it.');
    process.exit(1);
  }
  console.log(`known issues: ${entries.length} entries, generated copy current${now === next ? '' : ' (commit order table differs only)'}`);
} else {
  fs.writeFileSync(OUT, next);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${entries.length} entries, ${history.length} commits`);
}
