// The Courtroom — the house panels (Phase 3.5): the named venire as REAL
// reasoning agents.
//
// The figures in the 3D room have names and voir-dire bios (three/
// venire-bios.ts). This module gives each one an authored REASONING layer —
// attitudes, life experience, cognitive style — so a trial can empanel the
// twelve you've met and their reactions, ballots, and deliberation turns are
// THESE people arguing in character. Saul distrusts your round numbers in
// the actual transcript; Frank prices your claim like the adjuster he was.
//
// THE RAIL HOLDS (spec §2.3): personality IS the sanctioned engine — the
// spec's own reasoning layer (§4), the thing attitudes-out-predict-
// demographics is about. Composition fields below appear on the panel sheet
// only; personaBlock renders reasoning alone, so nothing demographic enters
// any prompt. Life experiences are written occupational/biographical, never
// demographic.
//
// Attitude scales (1-7, §4): institutional_trust, claims_consciousness,
// authority_orientation, risk_tolerance, corporate_skepticism,
// personal_responsibility_ethic.

import type {
  CognitiveStyle, CommunicationStyle, JurorComposition, JurorProfile,
  SalienceBias,
} from './types.ts';

function juror(
  seat: number,
  display_name: string,
  composition: JurorComposition,
  occupation_detail: string,
  life_experiences: string[],
  attitudes: [number, number, number, number, number, number],
  styles: [CognitiveStyle, CommunicationStyle, SalienceBias],
  backstory: string,
  register: string,
): JurorProfile {
  const [institutional_trust, claims_consciousness, authority_orientation,
    risk_tolerance, corporate_skepticism, personal_responsibility_ethic] = attitudes;
  return {
    id: `house-${seat}`, // replaced with a real UUID at empanelment
    seat,
    display_name,
    composition,
    reasoning: {
      occupation_detail,
      life_experiences,
      attitudes: {
        institutional_trust, claims_consciousness, authority_orientation,
        risk_tolerance, corporate_skepticism, personal_responsibility_ethic,
      },
      cognitive_style: styles[0],
      communication: styles[1],
      salience_bias: styles[2],
    },
    voice: { backstory, register },
  };
}

